  const I18N = {
    LANGUAGES,
    DEFAULT_LANG,
    STORAGE_KEY,
    TRANSLATIONS,

    /** Returns the current language code, persisted or detected. */
    getLang() {
      try {
        const stored = localStorage.getItem(STORAGE_KEY);
        if (stored && TRANSLATIONS[stored]) return stored;
      } catch (_) { /* localStorage may be blocked */ }

      // Detect browser language
      const nav = (navigator.language || navigator.userLanguage || '').toLowerCase();
      if (nav.startsWith('zh')) return 'zh';
      if (nav.startsWith('en')) return 'en';
      if (nav.startsWith('ja')) return 'ja';
      if (nav.startsWith('ko')) return 'ko';
      if (nav.startsWith('es')) return 'es';
      return DEFAULT_LANG;
    },

    /** Persist a language code. */
    setLang(code) {
      if (!TRANSLATIONS[code]) return;
      try { localStorage.setItem(STORAGE_KEY, code); } catch (_) { /* noop */ }
    },

    /** Translate a key. Falls back to English, then to the key itself. */
    t(key, lang) {
      const dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];
      if (dict && dict[key] != null) return dict[key];
      const fallback = TRANSLATIONS.en;
      if (fallback && fallback[key] != null) return fallback[key];
      return key;
    },

    /** Find the language meta object by code. */
    info(code) {
      return LANGUAGES.find(l => l.code === code) || LANGUAGES[0];
    },
  };

  root.PongPathI18n = I18N;
